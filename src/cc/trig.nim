proc sinQ16*(angle: int64): int64 =
  ## `sin(a)` in Q16 for a Q16 angle, by integer quadrant reduction and linear
  ## interpolation over the committed table. Odd, 2*PI-periodic, and exact to
  ## within 2 Q16 units of `math.sin` (tests/test_cc_sim.nim 3).
  ##
  ## The angle is mapped onto the table's own index space in Q16 rather than
  ## divided by a rounded step: `HalfPiQ16` is not an exact multiple of any
  ## integer step, so a fixed step would leave a wider final interval and a
  ## discontinuity at PI/2.
  var a = wrapAngle(angle)
  var sign = 1'i64
  if a < 0:
    a = -a
    sign = -1
  ## `a` is now in [0, PI]. Fold the second quadrant onto the first.
  if a > HalfPiQ16:
    a = PiQ16 - a
  if a < 0:
    a = 0
  ## Position in table-index space, Q16. a <= HalfPiQ16 so the product is at
  ## most 102 944 * 1024 * 65 536 = 6.9e12, three orders inside int64.
  let scaled = (a * QuadrantSteps * OneQ16) div HalfPiQ16
  var index = scaled div OneQ16
  if index >= QuadrantSteps:
    return sign * OneQ16
  let
    frac = scaled - index * OneQ16
    lo = int64(SinQ16Table[int(index)])
    hi = int64(SinQ16Table[int(index) + 1])
  sign * (lo + ((hi - lo) * frac) div OneQ16)

proc cosQ16*(angle: int64): int64 {.inline.} =
  sinQ16(angle + HalfPiQ16)

proc clampQ*(value, lo, hi: int64): int64 {.inline.} =
  if value < lo: lo elif value > hi: hi else: value

proc absQ*(value: int64): int64 {.inline.} =
  if value < 0: -value else: value
