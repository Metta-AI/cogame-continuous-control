## The sim's ONLY trigonometry and the ONLY fixed-point arithmetic helpers.
##
## Everything dynamical in this game is an `int64` holding a Q16 fixed-point SI
## value (65 536 = 1.0), in metres, seconds, kilograms, radians and their
## derived units. There is no `sin`, `cos`, `arctan2`, `sqrt` or `float`
## anywhere in this file or in any other hashed module — that is what makes the
## native amd64 server and the emscripten/wasm32 replay viewer agree bit for bit
## rather than depending on two builds of libm agreeing.
##
## TWO ARITHMETIC RULES, both grep-enforced (tests/test_cc_sim.nim 1, 2, 13):
##
##  1. `mulQ(a, b) = (a * b) div 65_536`, using `div`, NEVER `shr`. Nim's `shr`
##     on signed integers is a portability trap; `div` truncates toward zero on
##     every backend, is symmetric under negation, and is what makes native and
##     wasm32 agree. There is no `shr` on a signed value anywhere in the sim.
##  2. Every Q16 quantity is range-checked into its declared envelope once per
##     tick, which bounds every product in the solver under 2^62 with three
##     orders of magnitude of headroom.
##
## `SinQ16Table[k]` is `round(65536 * sin(k * PI / 2048))` for k in 0..1024 —
## one quadrant at 1/4096 of a turn. Generated once by `tools/gen_trig_table.nim`
## and checked in; `sinQ16` reduces an angle to a quadrant by integer arithmetic
## and interpolates linearly between two entries.

const
  OneQ16* = 65_536'i64
  HalfQ16* = 32_768'i64
  PiQ16* = 205_887'i64          ## round(PI * 65536)
  TwoPiQ16* = 2 * PiQ16
    ## EXACTLY twice `PiQ16`, not `round(2*PI * 65536)`: `wrapAngle` maps into
    ## the half-open range `(-PI, +PI]`, and a period that is one unit wider
    ## than twice the half-period leaves `-PiQ16` mapping to `PiQ16 + 1`, which
    ## is outside the range the step-8 invariant guard asserts. The 0.6/65536
    ## rad of period error this trades for is three orders below the table's
    ## own resolution.
  HalfPiQ16* = 102_944'i64      ## round(PI/2 * 65536)
  QuadrantSteps* = 1024'i64
    ## Table entries per quadrant. One step is PI/2048 rad = 15.3 urad * 100.
  DegToQ16Num* = 205_887'i64    ## degrees -> Q16 radians: * PiQ16 div 180
  DegToQ16Den* = 180'i64

proc mulQ*(a, b: int64): int64 {.inline.} =
  ## The ONE fixed-point product. `div`, never `shr`: truncation toward zero is
  ## symmetric under negation on every backend, which a right shift is not.
  (a * b) div OneQ16

proc divQ*(a, b: int64): int64 {.inline.} =
  ## The ONE fixed-point quotient. A zero divisor returns 0 rather than
  ## trapping: every caller guards its denominator first (the solver's
  ## `DetEpsQ16` check), and a trap inside the wasm viewer is invisible.
  if b == 0: 0'i64 else: (a * OneQ16) div b

proc degQ16*(degrees: int64): int64 {.inline.} =
  ## Whole degrees as Q16 radians.
  (degrees * DegToQ16Num) div DegToQ16Den

proc wrapAngle*(a: int64): int64 =
  ## Wraps a Q16 angle into `(-PI, +PI]`. Idempotent, and total over the whole
  ## int64 range that the envelope guard admits.
  var v = a mod TwoPiQ16
  while v > PiQ16:
    v -= TwoPiQ16
  while v <= -PiQ16:
    v += TwoPiQ16
  v

